// node scripts/gen-offers-public-view.mjs > ../akay-ops/db/migrations/008_offers_public.sql
//
// Generates migration 008 FROM PG_FIELDS, so the database-side allowlist and
// the application-side allowlist cannot drift apart by hand. Re-run it whenever
// FIELDS/PG_FIELDS change and commit the result.
import { PG_FIELDS } from '../src/data/airtable.mjs';

const cols = PG_FIELDS.map(([name, col]) => {
  const bare = col.replace(/^[a-z]+\./, '');
  // Comma BEFORE the comment. A trailing `-- name` eats the separator and the
  // whole list collapses into one column expression.
  return `  ${col.padEnd(32)} as ${(bare + ',').padEnd(29)} -- ${name}`;
}).join('\n');

process.stdout.write(`-- 008_offers_public.sql
-- GENERATED by scripts/gen-offers-public-view.mjs in the Akay site repo.
-- Do not hand-edit the column list; change FIELDS/PG_FIELDS and regenerate.
--
-- WHY THIS EXISTS. Phase 3 points akay.ie at akay.offers, and the snapshot the
-- build bakes is committed to a PUBLIC repo. akay.offers holds buy_price,
-- margin_pct, supplier_name, supplier_email, supplier_payment_terms,
-- trader_comment and notes.
--
-- Until now the only thing standing between those columns and a public git
-- history was an application-side allowlist guarded by a regex. On 2026-09-23
-- that guard was broken, fixed, broken differently and fixed again inside two
-- hours, with the test suite green at every step - and one of those states
-- would have published buy prices under the field name "Public Note". A
-- denylist that has to anticipate every shape a cost column might take is the
-- wrong structure for this job.
--
-- So the grant moves. readonly_site loses SELECT on akay.offers entirely and
-- gets it on this view alone. A leak stops being something the regex prevents
-- and becomes something the role cannot express: \`select *\` through this view
-- returns public columns, because there is nothing else to return.
--
-- SECURITY_INVOKER IS DELIBERATELY OFF. akay.offers_computed sets
-- security_invoker = true, which checks permissions as the CALLER - so a view
-- built that way would still require readonly_site to hold SELECT on the base
-- table, and the base table is exactly what we are hiding. This view therefore
-- runs as its owner (postgres). That is the whole mechanism; do not "fix" it.
--
-- THE THREE FLAGS AT THE BOTTOM are filter columns, not display columns. The
-- delisted archive query needs them in its WHERE. They are operational state,
-- not commercial data, and none of them is in FORBIDDEN_FIELDS - but they are
-- deliberately NOT in PG_FIELDS, so they are never selected into the snapshot.

begin;

create or replace view akay.offers_public as
select
  o.airtable_id                    as airtable_id,
${cols}
  -- Filter-only. Never selected into the snapshot; see PG_FIELDS.
  c.is_expired                     as is_expired,
  o.status                         as status,
  o.offer_approval_status          as offer_approval_status,
  o.listing_approved               as listing_approved
from akay.offers o
join akay.offers_computed c on c.id = o.id;

comment on view akay.offers_public is
  'The ONLY object akay.ie may read. Generated from PG_FIELDS in src/data/airtable.mjs. Runs as owner on purpose, so readonly_site never needs SELECT on akay.offers.';

-- The grant moves to the view, and only the view.
grant select on akay.offers_public to readonly_site;

revoke all privileges on akay.offers          from readonly_site;
revoke all privileges on akay.offers_computed from readonly_site;
revoke all privileges on akay.offers_deleted  from readonly_site;

-- The site has no business reading these at all. Nothing uses readonly_site
-- yet - akay.ie has not been switched - so this is a tightening, not a change.
revoke all privileges on akay.clients        from readonly_site;
revoke all privileges on akay.clients_active from readonly_site;
revoke all privileges on akay.capsule_archive from readonly_site;

commit;

-- Verification. Expect exactly one row: offers_public / SELECT.
select table_name, string_agg(distinct privilege_type, ',') as privileges
from information_schema.role_table_grants
where table_schema = 'akay' and grantee = 'readonly_site'
group by table_name
order by table_name;
`);
